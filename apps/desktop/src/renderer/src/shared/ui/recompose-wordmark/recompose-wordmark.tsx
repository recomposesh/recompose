const WORD_INK = { x: 42, width: 222 };

const LETTERS = { top: 15, bottom: 37.272 };

const DESCENDER_BOTTOM = 47.88;

const LETTERS_HEIGHT = LETTERS.bottom - LETTERS.top;

const LETTERS_MIDDLE = (LETTERS.top + LETTERS.bottom) / 2;

const BOX_TOP = LETTERS_MIDDLE - (DESCENDER_BOTTOM - LETTERS_MIDDLE);

const BOX_HEIGHT = DESCENDER_BOTTOM - BOX_TOP;

/**
 * The app's name as the brand sets it, drawn rather than typed.
 *
 * @summary The paths are the wordmark's own, so the name reads the same in the app as on the site
 * rather than in whatever face the platform hands the chrome. It carries the word alone: the web
 * lockup draws the note beside it, and here the mark already stands there in its own colors. The
 * ink is whatever the surface is set in, because this stands in a band whose ink already quiets.
 *
 * The box is padded above by as far as `p` reaches below the line, so the letters sit in the
 * middle of it. Only one letter descends, so a box drawn to the ink hangs lower than the word
 * looks, and anything centring that box stands the name above whatever it is set beside. The size
 * follows the letters for the same reason: a caller lining this up with a mark is matching what
 * reads, not what the box measures.
 */
export function RecomposeWordmark({ letters = 8 }: { letters?: number }) {
  const drawnAt = letters / LETTERS_HEIGHT;

  return (
    <svg
      aria-label="recompose"
      fill="none"
      height={BOX_HEIGHT * drawnAt}
      role="img"
      viewBox={`${WORD_INK.x} ${BOX_TOP} ${WORD_INK.width} ${BOX_HEIGHT}`}
      width={WORD_INK.width * drawnAt}
      xmlns="http://www.w3.org/2000/svg"
    >
      {WORD.map((drawn) => (
        <path d={drawn} fill="currentColor" key={drawn.slice(0, 12)} />
      ))}
    </svg>
  );
}
